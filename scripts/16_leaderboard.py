#!/usr/bin/env python3
"""16_leaderboard.py -- deterministic, ranked view of results/metrics.csv.

What this is
  A MoleculeACE-style leaderboard rendered from the shipped per-seed grid
  (`results/metrics.csv`): one table per dataset x protocol, models ranked by
  mean test RMSE over seeds (lower is better), ties broken by mean MAE and
  then by model name so the output is byte-stable across reruns.

What this is NOT
  Not a cross-protocol ranking. The headline of this repository is that the
  split protocol moves the number more than the model does (README section 4
  and 11_variance_decomposition.py); reading one column of this leaderboard
  as "model quality" would contradict it. Only ranks *within* a table are
  meaningful.

Self-check before writing
  If `results/metrics_by_protocol.csv` (written by 07_report.py) exists, its
  rmse_mean / n_seeds must match the aggregation recomputed here, or the
  script stops with an error instead of publishing a second, conflicting
  number.

Usage
  python scripts/16_leaderboard.py
  -> writes results/leaderboard.md (no timestamps; same input => same bytes)
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"

PROTOCOL_ORDER = ["random", "temporal", "scaffold", "cold_drug", "cold_target"]
NULL_MODELS = {"mean", "mean_ligand_train", "mean_target_train"}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    src = RES / "metrics.csv"
    m = pd.read_csv(src)

    agg = (
        m.groupby(["dataset", "protocol", "model"])
        .agg(
            n_seeds=("seed", "nunique"),
            rmse_mean=("rmse", "mean"),
            rmse_sd=("rmse", "std"),
            mae_mean=("mae", "mean"),
            spearman_mean=("spearman_rho", "mean"),
            ci_harrell_mean=("ci_harrell", "mean"),
        )
        .reset_index()
    )
    # single-seed rows (the null baselines) have no std by definition; show them
    # as n/a rather than 0.0, which would read as "measured to be stable".
    agg["rmse_sd"] = agg["rmse_sd"].where(agg["n_seeds"] > 1)

    mbp_path = RES / "metrics_by_protocol.csv"
    if mbp_path.exists():
        mbp = pd.read_csv(mbp_path)
        j = agg.merge(
            mbp[["dataset", "protocol", "model", "rmse_mean", "n_seeds"]],
            on=["dataset", "protocol", "model"],
            suffixes=("_here", "_07"),
        )
        bad = j[(j["rmse_mean_here"] - j["rmse_mean_07"]).abs() > 5e-4]
        assert bad.empty, (
            f"leaderboard aggregation disagrees with metrics_by_protocol.csv on "
            f"{len(bad)} rows, e.g.:\n{bad.head()}"
        )

    L = [
        "# Leaderboard (seed-averaged, per protocol)",
        "",
        f"Generated by `scripts/16_leaderboard.py` from `results/metrics.csv` "
        f"(sha256 `{sha256(src)[:16]}...`). Re-run with "
        "`python scripts/16_leaderboard.py`; the file carries no timestamps, so the same "
        "input reproduces it byte-for-byte.",
        "",
        "**Ranking metric:** mean test RMSE over the available seeds, lower is better; "
        "ties broken by mean MAE, then model name. **Only ranks within one table are "
        "meaningful** - across protocols the split moves the number more than the model "
        "does (README section 4), so do not compare ranks between tables.",
        "",
        "`n` is the number of seeds averaged (3 for the learned models, 1 for the null "
        "baselines, which are deterministic and therefore have no measured seed spread); "
        "CI is the Harrell calibre (tied pairs dropped). Per-seed rows stay in "
        "`results/metrics.csv`; seed spreads are quoted honestly in README section 10.",
        "",
    ]

    for dataset in ["davis", "kiba"]:
        L += [f"## {dataset.upper()}", ""]
        for protocol in PROTOCOL_ORDER:
            tab = agg[(agg["dataset"] == dataset) & (agg["protocol"] == protocol)].copy()
            assert not tab.empty, f"no rows for {dataset}/{protocol}"
            tab = tab.sort_values(
                ["rmse_mean", "mae_mean", "model"], kind="mergesort"
            ).reset_index(drop=True)
            tab["rank"] = tab.index + 1
            L += [f"### protocol: `{protocol}`", ""]
            L += [
                "| rank | model | RMSE | seed SD | n | MAE | Spearman rho | CI (Harrell) |",
                "|---:|---|---:|---:|---:|---:|---:|---:|",
            ]
            for _, r in tab.iterrows():
                sd = "n/a" if pd.isna(r["rmse_sd"]) else f"{r['rmse_sd']:.4f}"
                # a constant predictor has an undefined rank correlation: show n/a, not nan
                rho = "n/a" if pd.isna(r["spearman_mean"]) else f"{r['spearman_mean']:.4f}"
                tag = " *(null)*" if r["model"] in NULL_MODELS else ""
                L.append(
                    f"| {r['rank']} | `{r['model']}`{tag} | {r['rmse_mean']:.4f} | {sd} "
                    f"| {r['n_seeds']} | {r['mae_mean']:.4f} | {rho} "
                    f"| {r['ci_harrell_mean']:.4f} |"
                )
            L += [""]

    out = RES / "leaderboard.md"
    out.write_bytes("\n".join(L).encode("utf-8"))
    print(f"wrote {out} ({out.stat().st_size} bytes, sha256 {sha256(out)[:16]}...)")


if __name__ == "__main__":
    main()
